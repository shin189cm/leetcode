def solution(A: list[int]) -> int:
    """
    Problem: codility_number_solitaire.py
        マス 0 から N-1 まで、サイコロ（1〜6）で前に進む。止まったマスの数の合計を最大にする。
        マス 0 から始まり、マス N-1 に止まったときだけゲームが終わる。
    URL: https://app.codility.com/programmers/lessons/17-dynamic_programming/number_solitaire/
    Difficulty: Codility Lessons 17（Dynamic programming）の課題
    Category: Dynamic Programming

    Complexity:
    - Time: O(N)
        - 各マスで見るのは手前の最大6個で、N に関係なく決まった数なので、1マスあたり O(1)
        - それを N 回くり返すので O(N)
    - Space: O(N)
        - dp 配列の長さが N
        - 手前6個しか使わないので、長さ6の入れ物（deque など）に減らせば O(1) にできる

    Approach:
    1. dp の定義
        - dp[i]：石がマス i に止まった（マス i に印が付いた）ときの、それまでの合計の最大値
        - A[i] を必ず足す前提にすると、「そのマスに止まる」ことと値がずれない
    2. 漸化式
        - マス i の直前に止まれるのは i-6 〜 i-1 のどれか
        - dp[0] = A[0]
        - dp[i] = A[i] + max(dp[i-6] 〜 dp[i-1])（i-6 が 0 より小さいときは 0 から）
    3. 答え
        - ゲームはマス N-1 に止まったときしか終わらないので、答えは dp[N-1] だけ

    memo:
    - 2026-11-20 Codility の Lessons で、ヒントありでAC（提出結果 100%、約1時間）
    - dp[i] を「マス i に止まったときの最大値」とする方針は自力で立てた
    - 答えを max(dp[n-6:n]) としていた。ゲームは N-1 に止まったときしか終わらないので、dp[n-1] だけでよい
    - 負のマスに止まる dp[n-2] を候補に使うのが気持ち悪いと感じ、約30分止まった。
      dp[n-2] は候補の1つとして比べられるだけで、小さければ選ばれない。
      A = [0, -1, 3, -4, 1] で表を書くと、dp = [0, -1, 3, -1, 4]。dp[4] は dp[3] ではなく dp[2] = 3 を選ぶ
    - 頭の中だけで考えて止まったら、5行くらいの表を手で書いて dp を埋める
    - 範囲の端は max(0, i-6) で処理できるので、N が6以下の場合の特別扱いは要らない
    - 自分で作ったテストケース（答えを先にコメントに書いてから Run）：
      [0, 1] → 1 / [-10000, 10000] → 0 / [1, -100, -100, -100, -100, -100, 1] → 2（6マスちょうど跳ぶ）
      [1, -100, -100, -100, -100, -100, -100, 1] → -98（途中で1回は止まる）
    - 値の範囲 [−10,000..10,000] は両端を含む。「未満」と読み違えない
    - 提出前に、docstring とコメントを最終のコードに合わせる（過程も見られるテストでは特に）
    """
    n = len(A)
    dp = [0] * n
    dp[0] = A[0]

    for i in range(1, n):
        # 直前に止まれるのは i-6 〜 i-1 のどれか。その中の最大に A[i] を足す
        dp[i] = A[i] + max(dp[max(0, i - 6):i])

    # ゲームはマス N-1 に止まったときしか終わらない
    return dp[n - 1]


if __name__ == "__main__":
    tests = [
        ([1, -2, 0, 9, -1, -2], 8),
        ([0, -1, 3, -4, 1], 4),
        ([0, 1], 1),
        ([-10000, 10000], 0),
        ([1, -100, -100, -100, -100, -100, 1], 2),
        ([1, -100, -100, -100, -100, -100, -100, 1], -98),
    ]
    for A, expected in tests:
        assert solution(A) == expected, (A, solution(A), expected)
    print("all tests passed")
