coins = [(10, a), (2, b), (1, c)]  # (額面, 上限枚数)

dp = [0] * (x + 1)
dp[0] = 1

for v, n in coins:
    ndp = [0] * (x + 1)          # このコインを使った後の表
    for s in range(x + 1):
        if dp[s] == 0:
            continue
        for t in range(n + 1):   # このコインを t 枚使う
            ns = s + v * t
            if ns > x:
                break
            ndp[ns] += dp[s]
    dp = ndp

print(dp[x])
